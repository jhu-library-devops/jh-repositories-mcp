/**
 * Shared helpers for the documentation scripts: repository paths, Markdown
 * table rendering, front-matter parsing, and git queries.
 */

import { existsSync, readFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

export const REPO_ROOT: string = resolve(import.meta.dir, "..", "..");
export const DOCS_ROOT: string = join(REPO_ROOT, "docs");

/** Directories under docs/ that are working records, not published pages. */
export const UNPUBLISHED_DOC_DIRS: readonly string[] = ["docs/spike/"];

/** Front matter and notice that open every generated page. */
export const GENERATED_BANNER = [
  "---",
  "editLink: false",
  "---",
  "",
  "<!-- Generated by scripts/docs/generate.ts from source. Do not edit by hand; run `bun run docs:generate`. -->",
].join("\n");

export class DocsScriptError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "DocsScriptError";
  }
}

/** Escape a value for use inside a Markdown table cell. */
export function cell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();
}

/** Render a Markdown table. Every row must have the same width as the header. */
export function table(header: readonly string[], rows: readonly (readonly string[])[]): string {
  const lines = [
    `| ${header.map(cell).join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => {
      if (row.length !== header.length) {
        throw new DocsScriptError(`Table row has ${row.length} cells, expected ${header.length}`);
      }
      return `| ${row.map(cell).join(" | ")} |`;
    }),
  ];
  return lines.join("\n");
}

/** Escape Markdown emphasis characters in prose copied from source comments or strings. */
export function prose(value: string): string {
  return value.replace(/([_*])/g, "\\$1");
}

export function code(value: string): string {
  return `\`${value}\``;
}

export function repoPath(absolutePath: string): string {
  return relative(REPO_ROOT, absolutePath).split("\\").join("/");
}

// ─── Front matter ────────────────────────────────────────────────────────────

export interface PageFrontMatter {
  readonly sources: readonly string[];
  readonly verified: string | null;
}

export interface MarkdownPage {
  readonly path: string;
  readonly frontMatter: PageFrontMatter;
  readonly body: string;
}

const FRONT_MATTER = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/;

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function toDateString(value: unknown): string | null {
  if (value instanceof Date) {
    return value.toISOString().slice(0, 10);
  }
  if (typeof value === "string" && /^\d{4}-\d{2}-\d{2}$/.test(value)) {
    return value;
  }
  return null;
}

/** Parse a page's YAML front matter, keeping only the keys the docs scripts use. */
export function parsePage(path: string): MarkdownPage {
  const text = readFileSync(join(REPO_ROOT, path), "utf8");
  const match = FRONT_MATTER.exec(text);
  if (match === null || match[1] === undefined) {
    return { path, frontMatter: { sources: [], verified: null }, body: text };
  }
  let parsed: unknown;
  try {
    parsed = Bun.YAML.parse(match[1]);
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    throw new DocsScriptError(`${path}: front matter is not valid YAML (${reason})`);
  }
  const data = isRecord(parsed) ? parsed : {};
  const rawSources = data.sources;
  if (rawSources !== undefined && !Array.isArray(rawSources)) {
    throw new DocsScriptError(`${path}: front matter "sources" must be a list of paths`);
  }
  const sources = (rawSources ?? []).map((entry: unknown) => {
    if (typeof entry !== "string" || entry.length === 0) {
      throw new DocsScriptError(`${path}: every "sources" entry must be a non-empty string`);
    }
    return entry;
  });
  const verified = data.verified === undefined ? null : toDateString(data.verified);
  if (data.verified !== undefined && verified === null) {
    throw new DocsScriptError(`${path}: front matter "verified" must be a YYYY-MM-DD date`);
  }
  return { path, frontMatter: { sources, verified }, body: text.slice(match[0].length) };
}

// ─── File discovery ──────────────────────────────────────────────────────────

/** Repo-relative paths of Markdown files matching a glob, sorted for determinism. */
export function markdownFiles(pattern: string): string[] {
  const glob = new Bun.Glob(pattern);
  return [...glob.scanSync({ cwd: REPO_ROOT, onlyFiles: true })]
    .map((path) => path.split("\\").join("/"))
    .filter((path) => !path.includes("node_modules/") && !path.includes("/.vitepress/"))
    .sort();
}

/** Published, hand-written pages: everything under docs/ except generated and unpublished ones. */
export function handWrittenPages(): string[] {
  return markdownFiles("docs/**/*.md").filter(
    (path) =>
      !path.startsWith("docs/reference/") &&
      !UNPUBLISHED_DOC_DIRS.some((dir) => path.startsWith(dir)),
  );
}

/** Expand a `sources` entry (a path or a glob) into the files it names. */
export function expandSource(source: string): string[] {
  if (/[*?[{]/.test(source)) {
    const glob = new Bun.Glob(source);
    return [...glob.scanSync({ cwd: REPO_ROOT, onlyFiles: true })].sort();
  }
  return existsSync(join(REPO_ROOT, source)) ? [source] : [];
}

// ─── Git ─────────────────────────────────────────────────────────────────────

export function git(args: readonly string[]): string {
  const result = Bun.spawnSync(["git", ...args], { cwd: REPO_ROOT, stderr: "pipe" });
  if (result.exitCode !== 0) {
    throw new DocsScriptError(`git ${args.join(" ")} failed: ${result.stderr.toString().trim()}`);
  }
  return result.stdout.toString().trim();
}
